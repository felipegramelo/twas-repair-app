"""
PDF Logo Regression Test

Bug context (2026-04-26): The timesheet PDF route was missing the import
`from PIL import Image as PILImage`, causing the logo to silently fail
loading (exception caught and logged, but PDF generated without logo).

This test validates that every PDF type generated by the backend contains
at least one image — preventing regression of "silent logo loss" bugs
across timesheets, service orders, reports, and boletim de medição PDFs.

Run: pytest /app/backend/tests/test_pdf_logo_regression.py -v
"""

import os
import io
import pytest
import requests
import fitz  # PyMuPDF

BASE_URL = os.environ.get(
    'REACT_APP_BACKEND_URL',
    'https://twas-repair-app-1.preview.emergentagent.com'
).rstrip('/')

ADMIN_EMAIL = "admin@twasrepair.com"
ADMIN_PASSWORD = "admin123"


@pytest.fixture(scope="module")
def admin_token():
    resp = requests.post(
        f"{BASE_URL}/api/auth/login",
        json={"email": ADMIN_EMAIL, "password": ADMIN_PASSWORD},
        timeout=15,
    )
    assert resp.status_code == 200, f"Login failed: {resp.text}"
    token = resp.json().get("access_token")
    assert token, "No access_token returned"
    return token


def _pdf_has_image(pdf_bytes: bytes) -> tuple[bool, int]:
    """Returns (has_image, image_count) across all pages."""
    doc = fitz.open(stream=pdf_bytes, filetype="pdf")
    total = 0
    for page in doc:
        total += len(page.get_images())
    doc.close()
    return total > 0, total


def _download_pdf(url: str, token: str) -> bytes:
    resp = requests.get(
        url,
        headers={"Authorization": f"Bearer {token}"},
        timeout=30,
    )
    assert resp.status_code == 200, f"PDF download failed ({url}): {resp.status_code} {resp.text[:200]}"
    assert resp.content.startswith(b"%PDF"), f"Response is not a PDF: {resp.content[:50]}"
    return resp.content


class TestPDFLogo:
    """Verify every PDF contains the company logo (>=1 embedded image)."""

    def test_timesheet_pdf_has_logo(self, admin_token):
        """REGRESSION: PILImage import bug — timesheet PDF must contain the logo."""
        ts_list = requests.get(
            f"{BASE_URL}/api/timesheets",
            headers={"Authorization": f"Bearer {admin_token}"},
            timeout=15,
        ).json()
        if not ts_list:
            pytest.skip("No timesheets in DB to test")

        ts_id = ts_list[0]["id"]
        pdf = _download_pdf(f"{BASE_URL}/api/timesheets/{ts_id}/pdf", admin_token)
        has_img, count = _pdf_has_image(pdf)
        assert has_img, f"Timesheet PDF {ts_id} has no embedded images (logo missing!)"
        print(f"[OK] Timesheet PDF: {count} image(s)")

    def test_service_order_pdf_has_logo(self, admin_token):
        """OS PDF must contain the logo."""
        os_list = requests.get(
            f"{BASE_URL}/api/service-orders",
            headers={"Authorization": f"Bearer {admin_token}"},
            timeout=15,
        ).json()
        if not os_list:
            pytest.skip("No service orders in DB to test")

        os_id = os_list[0]["id"]
        pdf = _download_pdf(f"{BASE_URL}/api/service-orders/{os_id}/pdf", admin_token)
        has_img, count = _pdf_has_image(pdf)
        assert has_img, f"Service Order PDF {os_id} has no embedded images (logo missing!)"
        print(f"[OK] Service Order PDF: {count} image(s)")

    def test_report_pdf_has_logo(self, admin_token):
        """Report PDF must contain the logo."""
        resp = requests.get(
            f"{BASE_URL}/api/reports",
            headers={"Authorization": f"Bearer {admin_token}"},
            timeout=15,
        ).json()
        reports = resp.get("reports", []) if isinstance(resp, dict) else resp
        if not reports:
            pytest.skip("No reports in DB to test")

        report_id = reports[0]["id"]
        pdf = _download_pdf(f"{BASE_URL}/api/reports/{report_id}/pdf", admin_token)
        has_img, count = _pdf_has_image(pdf)
        assert has_img, f"Report PDF {report_id} has no embedded images (logo missing!)"
        print(f"[OK] Report PDF: {count} image(s)")

    def test_bm_pdf_has_logo(self, admin_token):
        """REGRESSION: PILImage import bug — Boletim de Medição PDF must contain the logo."""
        resp = requests.get(
            f"{BASE_URL}/api/bm",
            headers={"Authorization": f"Bearer {admin_token}"},
            timeout=15,
        ).json()
        bms = resp.get("bms", []) if isinstance(resp, dict) else resp
        if not bms:
            pytest.skip("No Boletins de Medição in DB to test")

        bm_id = bms[0]["id"]
        pdf = _download_pdf(f"{BASE_URL}/api/bm/{bm_id}/pdf", admin_token)
        has_img, count = _pdf_has_image(pdf)
        assert has_img, f"BM PDF {bm_id} has no embedded images (logo missing!)"
        print(f"[OK] Boletim de Medição PDF: {count} image(s)")
